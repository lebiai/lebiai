export type TranslationKey = keyof typeof dictionaries[typeof DEFAULT_LANGUAGE];

export function normalizeLanguage(language: string | null | undefined): Language {
  return language === "zh-CN" ? "zh-CN" : DEFAULT_LANGUAGE;
}

export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  let value: string = dictionaries[language][key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}
